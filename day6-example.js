// 과제 1. 음식 추가
const foods = [
    "피자",
    "치킨",
    "햄버거"
];
// push()를 사용하여
// 초밥
// 을 추가하세요.
foods.push("초밥");
console.log(foods);
/*----------------------------------------------------------------------------------------------------*/
// 과제 2. 마지막 음식 삭제
// pop()을 사용하세요.
foods.pop();
console.log(foods);
/*----------------------------------------------------------------------------------------------------*/
// 과제 3. 앞에 음식 추가
// unshift()를 사용하여
// 라면
// 을 추가하세요.
foods.unshift("라면");
console.log(foods);
