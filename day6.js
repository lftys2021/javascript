/*----------------------------------------------------------------------------------------------------*/
// 1. 배열(Array)이란?
// 배열은 여러 개의 데이터를 순서대로 저장하는 자료형입니다.
const fruits = [
    "사과",
    "배",
    "포도"
];
/*----------------------------------------------------------------------------------------------------*/
// 2. 요소 접근
// 인덱스(Index)는 0부터 시작합니다.
console.log(fruits[0]);
console.log(fruits[1]);
console.log(fruits[2]);
// 출력
// 사과
// 배
// 포도
// 마지막 요소
console.log(fruits[fruits.length - 1]);
// 또는
console.log(fruits.at(-1));
/*----------------------------------------------------------------------------------------------------*/
// 3. 요소 수정
fruits[1] = "바나나";
console.log(fruits);
// 결과
// ["사과", "바나나", "포도"]
/*----------------------------------------------------------------------------------------------------*/
// 4. push()
// 배열 끝에 추가
fruits.push("수박");
console.log(fruits);
// 결과
// ["사과", "배", "포도", "수박"]
/*----------------------------------------------------------------------------------------------------*/
// 5. pop()
// 배열 끝 삭제
fruits.pop();
console.log(fruits);
/*----------------------------------------------------------------------------------------------------*/
// 6. unshift()
// 배열 앞에 추가
fruits.unshift("딸기");
console.log(fruits);
// 결과
// ["딸기", "사과", "배", "포도"]
/*----------------------------------------------------------------------------------------------------*/
// 7. shift()
// 배열 앞 삭제
fruits.shift();
console.log(fruits);
/*----------------------------------------------------------------------------------------------------*/
// 8. slice()
// 원본은 그대로 두고 일부를 복사합니다.
const numbers = [1,2,3,4,5];
console.log(numbers);
const result = numbers.slice(1,4);
console.log(result);
// 출력 [2,3,4]
// 원본 [1,2,3,4,5]
/*----------------------------------------------------------------------------------------------------*/
// 9. splice()
// 원본을 변경합니다.
const numbers1 = [1,2,3,4,5];
numbers1.splice(2,1);
console.log(numbers1);
// 출력 [1,2,4,5]
// 삽입
numbers1.splice(2,0,100);
console.log(numbers1);
// 출력 [1,2,100,4,5]
// 교체
numbers1.splice(2,1,999);
console.log(numbers1);
// 출력 [1,2,999,5]
/*----------------------------------------------------------------------------------------------------*/
// 10. forEach()
// 배열을 순회합니다.
const fruits1 = [
    "사과",
    "배",
    "포도"
];
fruits1.forEach(fruit => {
    console.log(fruit);
});
/*----------------------------------------------------------------------------------------------------*/
// 11. map()
// 새로운 배열을 만듭니다.
const numbers3 = [1,2,3];
console.log(numbers3);
const result3 = numbers3.map(num => num * 10);
console.log(result3);
// 출력 [10,20,30]
// 원본은 변경되지 않습니다.
/*----------------------------------------------------------------------------------------------------*/
// 12. filter()
// 조건에 맞는 것만 선택합니다.
const scores = [70,85,95,60];
const result2 = scores.filter(score => score >= 80);
console.log(result2);
// 출력 [85,95]
/*----------------------------------------------------------------------------------------------------*/
// 13. find()
// 첫 번째 요소 하나만 찾습니다.
const users = [
    {name:"홍길동"},
    {name:"김철수"},
    {name:"이영희"}
];
const user = users.find(u => u.name === "김철수");
console.log(user);
/*----------------------------------------------------------------------------------------------------*/
// 14. some()
// 하나라도 만족하면 true
const scores2 = [60,70,95];
console.log(scores2.some(score => score >= 90));
console.log(scores2.some(score => score >= 100));
// 출력 true
/*----------------------------------------------------------------------------------------------------*/
// 15. every()
// 모두 만족하면 true
console.log(scores2.every(score => score >= 60));
console.log(scores2.every(score => score >= 70));
// 출력 true
/*----------------------------------------------------------------------------------------------------*/
// 16. reduce()
// 값을 하나로 합칩니다.
const numbers4 = [1,2,3,4,5];
// array.reduce((누적값, 현재요소) => {...}, 초기값);
const sum = numbers4.reduce((acc,num)=>acc+num,0);
console.log(sum);
// 출력 15
// 평균
const avg = numbers4.reduce((a,b)=>a+b,2)/numbers4.length;
console.log(avg);
/*----------------------------------------------------------------------------------------------------*/
// 17. 객체 배열
// Vue에서 가장 많이 사용하는 형태입니다.
const students = [
    {
        name:"홍길동",
        score:90
    },
    {
        name:"김철수",
        score:80
    },
    {
        name:"이영희",
        score:95
    }
];
// 반복
for(const student of students){
    console.log(student.name, student.score);
}
