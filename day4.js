// }
// 호출
// hello();
// 출력
// 안녕하세요.
/*----------------------------------------------------------------------------------------------------*/
// 3. 매개변수(Parameter)
// 함수에 값을 전달할 수 있습니다.
// function hello(name) {
//     console.log(name + "님, 안녕하세요.");
// }
// 호출
// hello("홍길동");
// hello("김철수");
// 출력
// 홍길동님, 안녕하세요.
// 김철수님, 안녕하세요.
/*----------------------------------------------------------------------------------------------------*/
// 4. 여러 개의 매개변수
// function add(a, b) {
//     console.log(a + b);
// }
// 호출
// add(10, 20);
// add(5, 8);
// 출력
// 30
// 13
/*----------------------------------------------------------------------------------------------------*/
// 5. 반환값(Return)
// return은 결과를 돌려줍니다.
// function add(a, b) {
//     return a + b;
// }
// 사용
// const result = add(10, 20);
// console.log(result);
// 출력
// 30
