// 객체를 만들 수 있다.
// 객체의 속성(Property)에 접근할 수 있다.
// 객체의 값을 수정할 수 있다.
// 객체에 새로운 속성을 추가하거나 삭제할 수 있다.
// 객체를 복사할 수 있다.
// 구조 분해 할당(Destructuring)을 사용할 수 있다.
// 객체 메서드(Object Method)를 만들 수 있다.
/*----------------------------------------------------------------------------------------------------*/
// 1. 객체(Object)란?
// 객체는 관련 있는 데이터를 하나로 묶은 것입니다.
// 예를 들어 학생 한 명을 표현하면
const student = {
    name: "홍길동",
    age: 20,
    major: "컴퓨터공학"
};
console.log(student);
// 이처럼 하나의 객체 안에 여러 정보를 저장합니다.
/*----------------------------------------------------------------------------------------------------*/
// 2. 객체 생성
const user = {
    name: "홍길동",
    age: 20,
    city: "서울"
};
// 출력
console.log(user);
/*----------------------------------------------------------------------------------------------------*/
// 3. 객체 속성(Property) 접근
// 점(.) 표기법
// 가장 많이 사용하는 방법입니다.
console.log(user.name);
console.log(user.age);
// 출력
// 홍길동
// 20
// 대괄호([]) 표기법
console.log(user["name"]);
console.log(user["city"]);
// 출력
// 홍길동
// 서울
/*----------------------------------------------------------------------------------------------------*/
// 4. 객체 값 수정
user.age = 21;
console.log(user.age);
console.log(user);
// 출력
// 21
/*----------------------------------------------------------------------------------------------------*/
// 5. 객체 속성 추가
user.job = "개발자";
console.log(user);
// 결과
// {
//     name: "홍길동",
//     age: 21,
//     city: "서울",
//     job: "개발자"
// }
/*----------------------------------------------------------------------------------------------------*/
// 6. 객체 속성 삭제
delete user.city;
console.log(user);
// 결과
// {
//     name: "홍길동",
//     age: 21,
//     job: "개발자"
// }
/*----------------------------------------------------------------------------------------------------*/
// 7. 객체 안에 객체
const student1 = {
    name: "홍길동",

    address: {
        city: "서울",
        zip: "12345"
    }
};
// 접근
console.log(student1.address.city);
// 출력
// 서울
/*----------------------------------------------------------------------------------------------------*/
// 8. 객체 안에 배열
const user1 = {
    name: "홍길동",

    hobbies: [
        "축구",
        "게임",
        "독서"
    ]
};
// 출력
console.log(user1.hobbies[0]);
// 결과
// 축구
/*----------------------------------------------------------------------------------------------------*/
// 9. 객체 메서드(Method)
// 객체 안에 함수를 넣을 수 있습니다.
const user2 = {
    name: "홍길동",

    hello() {
        console.log("안녕하세요.");
    }
};
user2.hello();
// 출력
// 안녕하세요.
/*----------------------------------------------------------------------------------------------------*/
// 10. 객체 반복
const user3 = {
    name: "홍길동",
    age: 20,
    city: "서울"
};
for (const key in user3) {
    console.log(key, user3[key]);
}
// 출력
// name 홍길동
// age 20
// city 서울
/*----------------------------------------------------------------------------------------------------*/
// 11. 객체 복사
// 잘못된 방법
const user5 = {
    name: "홍길동"
};
const user6 = user5;
user6.name = "김철수";
console.log(user5.name);
// 출력
// 김철수
// 왜냐하면 같은 객체를 가리키기 때문입니다.
// 올바른 방법
const user7 = {
    ...user5
};
// 또는
const user8 = Object.assign({}, user5);
/*----------------------------------------------------------------------------------------------------*/
// 12. Spread 문법
const user4 = {
    name: "홍길동",
    age: 20
};
const newUser4 = {
    ...user,
    city: "서울"
};
console.log(newUser4);
// 출력
// {
//     name: "홍길동",
//     age: 20,
//     city: "서울"
// }
/*----------------------------------------------------------------------------------------------------*/
// 13. 구조 분해 할당(Destructuring)
const user9 = {
    name: "홍길동",
    age: 20,
    city: "서울"
};
// 기존 방식
console.log(user9.name);
console.log(user9.age);
// 구조 분해
const { name, age } = user9;
console.log(name);
console.log(age);
// 출력
// 홍길동
// 20
/*----------------------------------------------------------------------------------------------------*/
// 14. Optional Chaining
// 객체가 없을 수도 있을 때
const user10 = null;
console.log(user10?.name);
// 출력
// undefined
/*----------------------------------------------------------------------------------------------------*/
// 15. 객체와 배열 함께 사용
const students2 = [
    {
        name: "홍길동",
        score: 90
    },
    {
        name: "김철수",
        score: 80
    },
    {
        name: "이영희",
        score: 95
    }
];
// 출력
for (const student of students2) {
    console.log(student.name, student.score);
}
// 결과
// 홍길동 90
// 김철수 80
// 이영희 95
/*----------------------------------------------------------------------------------------------------*/