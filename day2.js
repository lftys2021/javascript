/*----------------------------------------------------------------------------------------------------*/
// 10. OR(||)와의 차이
let name = "";
console.log(name || "이름 없음");
// 출력
// 이름 없음
// why? because "" is falsy (false) in JavaScript
// 반면
console.log(name ?? "이름 없음");
// 출력
// ??는 null과 undefined만 확인합니다.
/*----------------------------------------------------------------------------------------------------*/
// 11. Optional Chaining (?.)
// 객체가 없을 수도 있을 때 안전하게 접근하는 방법입니다.
const user = null;
console.log(user?.name);
// 출력
// undefined
// 만약 ?.를 사용하지 않으면
console.log(user.name);
// 오류가 발생합니다.
// TypeError: Cannot read properties of null
